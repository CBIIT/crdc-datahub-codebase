/**
 * Keys that are missing or not usable on parsed email YAML.
 * @param {unknown} parsed
 * @returns {string[]}
 */
function getInvalidEmailConstantKeys(parsed) {
    if (parsed == null || typeof parsed !== 'object' || Array.isArray(parsed)) {
        return ['<root>'];
    }
    const invalid = [];
    for (const key of REQUIRED_EMAIL_CONSTANT_STRING_KEYS) {
        const value = parsed[key];
        if (typeof value !== 'string' || value.trim() === '') {
            invalid.push(key);
        }
    }
    const additional = parsed.FINAL_INACTIVE_SUBMISSION_ADDITIONAL_CONTENT;
    // YAML sequences are not general-purpose email bodies. Do not add new array keys for copy.
    // FINAL_INACTIVE_SUBMISSION_ADDITIONAL_CONTENT is the only supported sequence: strings rendered
    // as separate paragraphs via Handlebars {{#each additionalMsg}}. HTML <ul>/<ol> inside YAML
    // strings is separate and needs block {{{ }}} injection in content-repo layouts.
    if (!Array.isArray(additional) || additional.length === 0
        || additional.some((item) => typeof item !== 'string' || item.trim() === '')) {
        invalid.push('FINAL_INACTIVE_SUBMISSION_ADDITIONAL_CONTENT');
    }
    return invalid;
}

